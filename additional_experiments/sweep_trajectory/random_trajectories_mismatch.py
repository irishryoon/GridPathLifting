"""
Generate 10 random trajectories for each of the 3 worlds (0-hole, 1-hole, 2-hole)
and compute mismatch scores for each.

Results are saved as a CSV with columns: world, trajectory_index, mismatch_score.

For the 1-hole world, pre-cached grid activity and traces are loaded from
DATA_ROOT/revision_cache/ (generated by revision/generate_1hole_trajectories.py).
"""

import os, sys
import numpy as np
import pandas as pd
import concurrent.futures as cf

sys.path.append(".")
from trajectory import random_walk, World
from grid_cell_simulation import preprocess, simulation
from pipelines import recover_traj_pipeline, compare_lifted_pipeline, segmental_compare_pipeline
from ROOT_PATH import DATA_ROOT


WORLD_SIZE = (100, 100)
HOLE_LOCATIONS = {
    0: None,
    1: [(30, 30, 70, 70)],
    2: [(10, 10, 45, 45), (55, 55, 90, 90)],
}
STEP_SIZE = 5
TRAJ_LENGTH = 25000
N_TRAJECTORIES = 10
SEG_LEN = 10000 # this is supposed to be 
CACHE_DIR = os.path.join(DATA_ROOT, "revision_cache")


def _run_single(n_holes: int, traj_idx: int) -> tuple[int, int, float, float, float]:
    """Run a single (world, trajectory) job.
    Returns (n_holes, traj_idx, mismatch_score, seg_mean, seg_std)."""
    if n_holes == 1:
        grid_activity = np.load(os.path.join(CACHE_DIR, f"grid_activity_{traj_idx}.npy"))
        processed_trace = np.load(os.path.join(CACHE_DIR, f"trace_{traj_idx}.npy"))
    else:
        world = World(WORLD_SIZE, HOLE_LOCATIONS[n_holes], step_size=STEP_SIZE)
        trace = random_walk(TRAJ_LENGTH, world, save=False, no_warnings=True)
        processed_trace = preprocess(trace, STEP_SIZE)
        grid_activity = simulation(processed_trace)
    # simulation uses diff for speeds, producing one fewer timestep than the trace
    processed_trace = processed_trace[:grid_activity.shape[1]]

    try:
        _, lifted = recover_traj_pipeline(grid_activity, method='dreimac')
        _, ms = compare_lifted_pipeline(lifted, processed_trace)
        seg_scores = segmental_compare_pipeline(lifted, processed_trace, SEG_LEN)
        seg_mean = float(np.mean(seg_scores))
        seg_std = float(np.std(seg_scores))
    except Exception as e:
        print(f"  world={n_holes}holes traj={traj_idx}: Pipeline failed ({e})")
        return n_holes, traj_idx, np.nan, np.nan, np.nan

    print(f"  world={n_holes}holes traj={traj_idx}: mismatch={ms:.6f}  seg_mean={seg_mean:.6f}")
    return n_holes, traj_idx, ms, seg_mean, seg_std


def main(save_dir: str = "impact_factors/sweep_trajectory/random_traj_results", max_workers: int = 6):
    os.makedirs(save_dir, exist_ok=True)

    jobs = [
        (n_holes, traj_idx)
        for n_holes in [0, 2]
        for traj_idx in range(N_TRAJECTORIES)
    ]
    print(f"Launching {len(jobs)} jobs ({N_TRAJECTORIES} trajectories, 1-hole world) ...")

    csv_path = os.path.join(save_dir, "mismatch_scores.csv")
    write_header = not os.path.exists(csv_path)

    results = []
    with cf.ProcessPoolExecutor(max_workers=max_workers) as executor:
        futures = {
            executor.submit(_run_single, n_holes, traj_idx): (n_holes, traj_idx)
            for n_holes, traj_idx in jobs
        }
        for future in cf.as_completed(futures):
            row = future.result()
            results.append(row)
            # Write incrementally so a crash doesn't lose completed results
            row_df = pd.DataFrame([row], columns=["world", "trajectory", "mismatch_score", "seg_mean", "seg_std"])
            row_df["world"] = row_df["world"].apply(lambda x: f"{x}holes")
            row_df.to_csv(csv_path, mode="a", header=write_header, index=False)
            write_header = False

    # Sort by (n_holes, traj_idx) for tidy output
    results.sort(key=lambda x: (x[0], x[1]))

    # Rewrite sorted CSV
    df = pd.DataFrame(results, columns=["world", "trajectory", "mismatch_score", "seg_mean", "seg_std"])
    df["world"] = df["world"].apply(lambda x: f"{x}holes")
    df.to_csv(csv_path, index=False)
    print(f"\nResults saved to {csv_path}")

    # Print summary
    for n_holes in sorted(HOLE_LOCATIONS):
        scores = [ms for nh, _, ms, _, _ in results if nh == n_holes and not np.isnan(ms)]
        if scores:
            print(
                f"  {n_holes}holes: mean={np.mean(scores):.6f}  "
                f"std={np.std(scores):.6f}  n_valid={len(scores)}/{N_TRAJECTORIES}"
            )
        else:
            print(f"  {n_holes}holes: all failed")


if __name__ == "__main__":
    main()
