N_TRAJECTORIES = 5
SEG_LEN = 10000
CACHE_DIR = os.path.join(DATA_ROOT, "revision_cache")
TRAJ_DIR = "/data/hyoon/GridDecode/trajectory"
GRID_DIR = "/data/hyoon/GridDecode/grid_fields"
