"""
Test the effect of lifting on mismatch scores:
1. No lifting: compute mismatch using raw toroidal coordinates (no lifting applied).
2. Random lifting: at each step where lifting would occur, randomly decide whether to lift or not.

Uses pre-cached grid activity and traces for the 1-hole world
(generated by revision/generate_1hole_trajectories.py, stored in DATA_ROOT/revision_cache/).
Also runs on Gardner (real) data.
Results saved as CSV.
"""

