GARDNER_RAT_NAME = "R"
GARDNER_MOD_NAME = "1"
GARDNER_DAY_NAME = "day2"
GARDNER_SESS_NAME = "OF"
GARDNER_SMOOTH_SIGMA = 10.0


def random_lifting(cir_coords: np.ndarray, seed: int | None = None) -> np.ndarray:
    """
    Same logic as toroidal_lifting_distance_upgrade, but at each point where
    a lift would be applied, randomly choose whether to actually lift or not.
    """
    rng = np.random.default_rng(seed)
    T = cir_coords.shape[0]

    # Draw per-step shifts: 1/3 chance each of 0, +2pi, -2pi; shape (T-1, 2)
    r = rng.integers(0, 3, size=(T - 1, 2))
    step_shifts = np.where(r == 1, 2 * np.pi, np.where(r == 2, -2 * np.pi, 0.0))

    # Applying cir_coords[i:] += shift is equivalent to adding the cumulative
    # sum of step_shifts at each position
    cir_coords = cir_coords.copy()
    cir_coords[1:] += np.cumsum(step_shifts, axis=0)
    return cir_coords




def _compare(coords: np.ndarray, processed_trace: np.ndarray) -> tuple[float, np.ndarray]:
    """Affine-align coords to processed_trace and return global mismatch and per-segment scores."""
    transform_mat = get_transform_mat(coords, processed_trace)
    transformed = apply_transform_mat(coords, transform_mat)
    mismatch = score_mismatch(transformed, processed_trace)
    seg_scores = segmental_mismatch(transformed, processed_trace, SEG_LEN)
    return mismatch, seg_scores


def _run_single(
    traj_idx: int,
    lifting_row: pd.Series | None = None,
    return_coords: bool = False,
) -> tuple:
    """
    Run a single trajectory for all three conditions.
    Lifting scores are loaded from lifting_row if provided, otherwise computed.
    Returns:
        (traj_idx,
         mismatch_lifting,    seg_mean_lifting,    seg_std_lifting,
         mismatch_no_lifting, seg_mean_no_lifting, seg_std_no_lifting,
         mismatch_random_lifting, seg_mean_random_lifting, seg_std_random_lifting
         [, coords_lifted, coords_no_lift, coords_random]  # only if return_coords=True
        )
    """
    traj_path = os.path.join(TRAJ_DIR, f"random_walk_1holes_25000_n{traj_idx}.pkl")
    with open(traj_path, "rb") as f:
        sim_result = pickle.load(f)
    processed_trace = preprocess(sim_result[0], goal=600000)

    activity_path = os.path.join(GRID_DIR, f"random_walk_1holes_25000_n{traj_idx}_grid_activity.npz")
    grid_activity = np.load(activity_path)["grid_activity"]
    tor_coord, _ = compute_toroidal_coords_dreimac(grid_activity.T)

    min_len = min(processed_trace.shape[0], tor_coord.shape[0])
    processed_trace = processed_trace[:min_len]
    tor_coord = tor_coord[:min_len]

    try:
        # 1. Proper lifting
        coords_lifted = toroidal_lifting_distance_upgrade(tor_coord.copy())
        _, ms_lift = compare_lifted_pipeline(coords_lifted, processed_trace)
        seg_scores_lift = np.array(segmental_compare_pipeline(coords_lifted, processed_trace, SEG_LEN))

        # 2. No lifting: use raw toroidal coordinates
        coords_no_lift = tor_coord.copy()
        ms_no_lift, seg_scores_no_lift = _compare(coords_no_lift, processed_trace)

        # 3. Random lifting
        coords_random = random_lifting(tor_coord.copy(), seed=traj_idx)
        ms_random_lift, seg_scores_random_lift = _compare(coords_random, processed_trace)

    except Exception as e:
        print(f"  traj={traj_idx}: Pipeline failed ({e})")
        nans = (traj_idx, np.nan, None, np.nan, None, np.nan, None)
        return nans + (None, None, None) if return_coords else nans

    print(
        f"  traj={traj_idx}: lift={ms_lift:.6f}  "
        f"no_lift={ms_no_lift:.6f}  random_lift={ms_random_lift:.6f}"
    )
    scores = (traj_idx, ms_lift, seg_scores_lift, ms_no_lift, seg_scores_no_lift, ms_random_lift, seg_scores_random_lift)
    if return_coords:
        return scores + (coords_lifted, coords_no_lift, coords_random)
    return scores


def _run_gardner(
    smooth_sigma: float = GARDNER_SMOOTH_SIGMA,
) -> tuple[float, float, float, float, float, float, float, float, float]:
    """
    Run lifting / no-lifting / random-lifting on Gardner data.
    Returns (ms_lift, seg_mean_lift, seg_std_lift,
             ms_no_lift, seg_mean_no_lift, seg_std_no_lift,
             ms_random_lift, seg_mean_random_lift, seg_std_random_lift)
    """
    sspikes, xx, yy, _, _ = get_spikes(
        GARDNER_RAT_NAME, GARDNER_MOD_NAME, GARDNER_DAY_NAME, GARDNER_SESS_NAME,
        bType="pure", bSmooth=True, bSpeed=True,
        folder=GARDNER_DATA_PATH,
    )
    original_coord = np.column_stack((xx, yy))

    cir_coords, _, _, _ = Gardner_coord(sspikes)
    tor_coord = cir_coords  # raw circular coordinates from Gardner pipeline

    def _smooth_and_compare(coords: np.ndarray) -> tuple[float, float, float]:
        coords = coords.copy()
        if smooth_sigma > 0:
            coords[:, 0] = gaussian_filter1d(coords[:, 0], smooth_sigma)
            coords[:, 1] = gaussian_filter1d(coords[:, 1], smooth_sigma)
        return _compare(coords, original_coord)

    # 1. Proper lifting
    coords_lifted = toroidal_lifting_distance_upgrade(tor_coord.copy())
    ms_lift, seg_mean_lift, seg_std_lift = _smooth_and_compare(coords_lifted)

    # 2. No lifting: raw toroidal coordinates
    ms_no_lift, seg_mean_no_lift, seg_std_no_lift = _smooth_and_compare(tor_coord.copy())

    # 3. Random lifting
    coords_random = random_lifting(tor_coord.copy(), seed=0)
    ms_random_lift, seg_mean_random_lift, seg_std_random_lift = _smooth_and_compare(coords_random)

    print(
        f"  Gardner: lift={ms_lift:.6f}  "
        f"no_lift={ms_no_lift:.6f}  random_lift={ms_random_lift:.6f}"
    )
    return (
        ms_lift, seg_mean_lift, seg_std_lift,
        ms_no_lift, seg_mean_no_lift, seg_std_no_lift,
        ms_random_lift, seg_mean_random_lift, seg_std_random_lift,
    )


def main_simulated(
    save_dir: str = "revision/random_lifting_test_results",
    n_trajectories: int = N_TRAJECTORIES,
    save_coords: bool = False,
):
    os.makedirs(save_dir, exist_ok=True)

    if os.path.exists(LIFTING_CSV):
        df_lifting = pd.read_csv(LIFTING_CSV)
        df_lifting = df_lifting[df_lifting["world"] == "1holes"]
        print(f"Loaded lifting scores from {LIFTING_CSV}")
    else:
        df_lifting = None
        print(f"Lifting CSV not found at {LIFTING_CSV}, will compute lifting scores.")

    def _lifting_row(idx: int) -> pd.Series | None:
        if df_lifting is not None:
            match = df_lifting[df_lifting["trajectory"] == idx]
            if not match.empty:
                return match.iloc[0]
        return None

    results = []
    for idx in tqdm(range(n_trajectories), desc="Trajectories"):
        results.append(_run_single(idx, _lifting_row(idx), return_coords=save_coords))

    rows = []
    for result in results:
        if save_coords:
            traj_idx, ms_lift, seg_scores_lift, ms_no_lift, seg_scores_no_lift, ms_random_lift, seg_scores_random_lift, coords_lifted, coords_no_lift, coords_random = result
            coords_dir = os.path.join(save_dir, "coords")
            os.makedirs(coords_dir, exist_ok=True)
            for name, arr in [("lift", coords_lifted), ("no_lift", coords_no_lift), ("random_lift", coords_random)]:
                if arr is not None:
                    np.save(os.path.join(coords_dir, f"traj{traj_idx}_{name}.npy"), arr)
            print(f"  Coordinates for traj={traj_idx} saved to {coords_dir}/")
        else:
            traj_idx, ms_lift, seg_scores_lift, ms_no_lift, seg_scores_no_lift, ms_random_lift, seg_scores_random_lift = result

        for method, ms, seg_scores in [
            ("lifting", ms_lift, seg_scores_lift),
            ("no_lifting", ms_no_lift, seg_scores_no_lift),
            ("random_lifting", ms_random_lift, seg_scores_random_lift),
        ]:
            if seg_scores is not None:
                for seg_idx, seg_score in enumerate(seg_scores):
                    rows.append((traj_idx, method, ms, seg_idx, float(seg_score)))
            else:
                rows.append((traj_idx, method, ms, np.nan, np.nan))

    df = pd.DataFrame(
        rows,
        columns=["trajectory", "method", "mismatch_score", "segment_index", "seg_score"],
    )
    csv_path = os.path.join(save_dir, "lifting_comparison.csv")
    df.to_csv(csv_path, index=False)
    print(f"\nResults saved to {csv_path}")

    for method in ["lifting", "no_lifting", "random_lifting"]:
        vals = df.loc[df["method"] == method, "mismatch_score"].drop_duplicates().dropna()
        if len(vals) > 0:
            print(
                f"  {method}: mean={vals.mean():.6f}  "
                f"std={vals.std():.6f}  n={len(vals)}/{N_TRAJECTORIES}"
            )
        else:
            print(f"  {method}: all failed")


def main_gardner(save_dir: str = "revision/random_lifting_test_results"):
    os.makedirs(save_dir, exist_ok=True)

    print("Running Gardner data...")
    try:
        (
            ms_lift, seg_mean_lift, seg_std_lift,
            ms_no_lift, seg_mean_no_lift, seg_std_no_lift,
            ms_random_lift, seg_mean_random_lift, seg_std_random_lift,
        ) = _run_gardner()
        gardner_rows = [
            (0, "lifting", ms_lift, seg_mean_lift, seg_std_lift),
            (0, "no_lifting", ms_no_lift, seg_mean_no_lift, seg_std_no_lift),
            (0, "random_lifting", ms_random_lift, seg_mean_random_lift, seg_std_random_lift),
        ]
    except Exception as e:
        print(f"  Gardner failed: {e}")
        gardner_rows = [
            (0, "lifting", np.nan, np.nan, np.nan),
            (0, "no_lifting", np.nan, np.nan, np.nan),
            (0, "random_lifting", np.nan, np.nan, np.nan),
        ]

    df_gardner = pd.DataFrame(
        gardner_rows,
        columns=["trajectory", "method", "mismatch_score", "seg_mean", "seg_std"],
    )
    gardner_csv_path = os.path.join(save_dir, "lifting_comparison_gardner.csv")
    df_gardner.to_csv(gardner_csv_path, index=False)
    print(f"Gardner results saved to {gardner_csv_path}")


def _scatter_groups(ax, groups, labels, colors, ylabel, title, jitter=0.08, errors=None):
    """Helper: scatter + mean±std errorbar for each group."""
    rng = np.random.default_rng(42)
    for pos, (data, color, label) in enumerate(zip(groups, colors, labels)):
        x = np.full_like(data, pos, dtype=float) + rng.uniform(-jitter, jitter, size=len(data))
        ax.scatter(x, data, s=50, color=color, edgecolors="none", label=label)
        mean = np.mean(data)
        err = errors[pos] if errors is not None else np.std(data)
        ax.errorbar(
            pos, mean, yerr=err, fmt="_", color="black",
            markersize=15, markeredgewidth=2, capsize=6, linewidth=1.5,
        )
    ax.set_xticks(range(len(labels)))
    ax.set_xticklabels(labels, fontsize=20)
    ax.tick_params(axis="y", labelsize=20)
    ax.set_ylabel(ylabel, fontsize = 20)
    ax.set_title(title, fontsize=22)
    ax.legend(fontsize = 16)


def plot_lifting_comparison(
    null_csv: str = "revision/random_lifting_test_results/lifting_comparison.csv",
    regular_csv: str = "revision/sweep_trajectory/random_traj_results/mismatch_scores.csv",
    world: str = "1holes",
    save_dir: str | None = None,
):
    """Plot mismatch scores for regular lifting vs no lifting vs random lifting."""
    if save_dir is None:
        save_dir = os.path.dirname(null_csv)

    df_null = pd.read_csv(null_csv)
    df_reg = pd.read_csv(regular_csv)
    df_null_unique = df_null.drop_duplicates(subset=["trajectory", "method"])

    regular_scores = np.asarray(
        df_null_unique.loc[df_null_unique["method"] == "lifting", "mismatch_score"].dropna()
    )
    no_lift = np.asarray(
        df_null_unique.loc[df_null_unique["method"] == "no_lifting", "mismatch_score"].dropna()
    )
    random_lift = np.asarray(
        df_null_unique.loc[df_null_unique["method"] == "random_lifting", "mismatch_score"].dropna()
    )

    fig, ax = plt.subplots(figsize=(8, 5))
    _scatter_groups(
        ax,
        groups=[regular_scores * 100, no_lift * 100, random_lift * 100],
        labels=["Lifting", "No Lifting", "Random Lifting"],
        colors=["#2196F3", "#E53935", "#FF9800"],
        ylabel="Global reconstruction error ( \%)",
        title=f"Lifting Comparison --- {world} world (n=5 each)",
    )
    fig.tight_layout()
    fig_path = os.path.join(save_dir, "lifting_comparison.pdf")
    plt.savefig(fig_path, dpi=200)
    print(f"Figure saved to {fig_path}")
    plt.show()


